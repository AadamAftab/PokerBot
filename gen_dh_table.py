"""Generate dh_table.py: 3-card preflop equity vs a random 3-card hand, both sides discarding by heuristic
after the flop, for every strategically distinct starting hand (rank multiset x suit pattern)."""
import itertools, sys, time
import numpy as np
import dhlib
from dhlib import keep_best, eval_best, triple_key

N = int(sys.argv[1]) if len(sys.argv) > 1 else 4000
rng = np.random.default_rng(7)
reps = {}
for t in itertools.combinations(range(52), 3):
    reps.setdefault(triple_key(*t), t)
print(len(reps), "classes", flush=True)

table = {}
t0 = time.time()
for i, (k, h) in enumerate(sorted(reps.items())):
    hole = np.array(h, dtype=np.int64)
    deck = dhlib._deck(set(h))
    d = dhlib._draw(deck, N, 8, rng)
    opp3, board = d[:, :3], d[:, 3:]
    flop = board[:, :3]
    _, okeep = keep_best(opp3, flop)
    _, hkeep = keep_best(np.broadcast_to(hole, (N, 3)), flop)
    mine = eval_best(np.concatenate([hkeep, board], axis=1))
    theirs = eval_best(np.concatenate([okeep, board], axis=1))
    table[k] = round(float(((mine > theirs) + 0.5 * (mine == theirs)).mean()), 4)
    if i % 200 == 0:
        print(i, f"{time.time()-t0:.0f}s", flush=True)

with open("dh_table.py", "w") as f:
    f.write("# generated by gen_dh_table.py (N=%d per class)\nTABLE = {\n" % N)
    for k, v in sorted(table.items()):
        f.write(f"    {k!r}: {v},\n")
    f.write("}\n")
print("done", len(table), f"{time.time()-t0:.0f}s")
