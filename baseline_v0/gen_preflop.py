"""Generate preflop_table.py: equity vs a random hand for all 169 starting-hand classes."""
import numpy as np
from pokerlib import equity

rng = np.random.default_rng(1)
table = {}
for hi in range(13):
    for lo in range(hi + 1):
        for suited in (False, True):
            if hi == lo and suited:
                continue
            if hi == lo:
                hole = [hi * 4, hi * 4 + 1]
            elif suited:
                hole = [hi * 4, lo * 4]
            else:
                hole = [hi * 4, lo * 4 + 1]
            table[(hi, lo, suited)] = round(equity(hole, [], n=6000, rng=rng), 4)

with open("preflop_table.py", "w") as f:
    f.write("# generated by gen_preflop.py\nTABLE = {\n")
    for k, v in sorted(table.items()):
        f.write(f"    {k!r}: {v},\n")
    f.write("}\n")
print(len(table), "classes")
